-- Formativa 1 - Servicio de biblioteca
-- Ejecutar como script (F5) en SQL Developer conectado como BIBLIOTECA_APP.
-- Preparacion inicial: el usuario debe existir y tener CREATE SESSION,
-- CREATE TABLE, CREATE SEQUENCE y cuota en el tablespace DATA.
-- Este script es para un esquema sin la tabla LIBROS.
-- No elimina ni reemplaza tablas existentes. No volver a ejecutar sobre
-- la base ya preparada: CREATE TABLE fallaria y el INSERT podria duplicarse.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE libros (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR2(255 CHAR),
    autor VARCHAR2(255 CHAR),
    anio_publicacion NUMBER(10),
    genero VARCHAR2(255 CHAR)
);

-- Los dos archivos originales de INSERT contenian el mismo libro.
-- Se conserva una sola insercion; Oracle genera el ID.
INSERT INTO libros (titulo, autor, anio_publicacion, genero)
VALUES ('El principito', 'Antoine de Saint-Exupéry', 1943, 'Fábula');

COMMIT;

SELECT id, titulo, autor, anio_publicacion, genero
FROM libros
ORDER BY id;
